// Concatenates supabase/migrations/*.sql (in order) into supabase/setup-all.sql so it can be pasted into the
// Supabase SQL editor in one go.   Run:  npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../supabase/migrations/', import.meta.url)
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const out = files.map((f) => `-- ════════════ ${f} ════════════\n${readFileSync(new URL(f, dir), 'utf8').trim()}\n`).join('\n')
writeFileSync(new URL('../supabase/setup-all.sql', import.meta.url), `-- GENERATED by scripts/bundle-sql.mjs — do not edit. Run once on a NEW, empty Supabase project.\n\n${out}`)
console.log(`Wrote supabase/setup-all.sql from ${files.length} migrations: ${files.join(', ')}`)
